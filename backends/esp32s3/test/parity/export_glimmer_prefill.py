"""Export four-token cached nano-Glimmer prefill for device parity/timing."""

import argparse
import json
import os

import torch

from executorch.backends.esp32s3.partition.espressif_partitioner import (
    Esp32Partitioner,
)
from executorch.backends.esp32s3._passes import apply_passes, lower_esp32
from executorch.backends.esp32s3.test.parity.export_glimmer_decode import (
    quantize_reference_modules,
    token_at,
)
from executorch.examples.espressif.esp32s3.story.glimmer_decode import build_prefill

from executorch.backends.esp32s3.test import firmware

HERE = os.path.dirname(os.path.abspath(__file__))
# The example firmware project embeds the programs from its main/.
MAIN = str(firmware.MAIN)


def checksum(logits):
    flat = logits.reshape(-1)
    return sum(float(flat[i]) * (i + 1) for i in range(flat.numel()))


def write_inputs(tokens, chunk_size):
    values = ", ".join(str(t) for t in tokens)
    path = os.path.join(MAIN, "prefill_inputs.h")
    with open(path, "w") as out:
        out.write(
            "// Generated by export_glimmer_prefill.py; do not edit.\n"
            "#pragma once\n"
            f"static constexpr int kPrefillTokens[] = {{{values}}};\n"
            f"static constexpr int kPrefillChunk = {chunk_size};\n"
            f"static constexpr int kPrefillSteps = {len(tokens) // chunk_size};\n"
        )


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--vocab", type=int, default=256)
    ap.add_argument("--seq-len", type=int, default=8)
    ap.add_argument("--chunk-size", type=int, default=4)
    args = ap.parse_args(argv)
    if args.seq_len % args.chunk_size:
        raise ValueError("seq_len must be divisible by chunk_size")

    common = dict(
        arm="ple", vocab=args.vocab, d_model=64, layers=4, heads=8,
        kv_heads=1, ffn=192, ple_dim=24, seq_len=args.seq_len,
        window=min(4, args.seq_len), softcap=20.0,
        chunk_size=args.chunk_size,
    )
    tokens = [token_at(i, args.vocab) for i in range(args.seq_len)]

    _, reference = build_prefill(**common, reference_dynamic_qk=True)
    quantize_reference_modules(reference)
    refs = []
    with torch.no_grad():
        for start in range(0, args.seq_len, args.chunk_size):
            chunk = torch.tensor(tokens[start:start + args.chunk_size])
            logits = reference(chunk, torch.tensor(start))
            got = checksum(logits)
            refs.append(got)
            print(f"  host prefill block {start // args.chunk_size}: "
                  f"pos {start:5d}..{start + args.chunk_size - 1:5d}  "
                  f"checksum {got:.6f}")

    cfg, model = build_prefill(**common)
    inputs = (torch.tensor(tokens[:args.chunk_size]), torch.tensor(0))
    edge = lower_esp32(
        torch.export.export(model, inputs),
        [Esp32Partitioner(
            external_weights="prefill_weights",
            quantize_qk=True,
            group_weights=False,
        )],
    )
    report = apply_passes(edge, rmsnorm_expect=7 * cfg.n_layers + 3)
    assert report["rope_fused"] == 6, report

    from executorch.exir import ExecutorchBackendConfig
    et_cfg = ExecutorchBackendConfig(
        delegate_alignment=16,
        constant_tensor_alignment=16,
        external_constants=lambda node: "prefill_weights",
    )
    program = edge.to_executorch(config=et_cfg)
    pte = os.path.join(MAIN, "prefill.pte")
    with open(pte, "wb") as out:
        out.write(program.buffer)

    program.write_tensor_data_to_file(MAIN)
    weight_path = os.path.join(MAIN, "prefill_weights.ptd")

    write_inputs(tokens, args.chunk_size)
    meta = {
        "architecture": "glimmer-ple-prefill",
        "vocab": args.vocab,
        "seq_len": args.seq_len,
        "chunk_size": args.chunk_size,
        "tokens": tokens,
        "checksums": refs,
    }
    with open(os.path.join(MAIN, "prefill_ref.json"), "w") as out:
        json.dump(meta, out, indent=1)
    print(f"wrote prefill.pte {os.path.getsize(pte):,} B + "
          f"prefill_weights.ptd {os.path.getsize(weight_path):,} B")
    return meta


if __name__ == "__main__":
    main()
