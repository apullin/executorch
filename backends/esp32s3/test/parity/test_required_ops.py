"""No dynamic chooser is ever registered as a portable kernel.

ExecuTorch's portable choose_qparams agrees with none of PyTorch's choosers
(it ignores eps, computes in float64 and picks its zero point by error), so a
chooser left outside the delegate would quantise differently from the model.
Two mechanisms keep it out: the exporter absorbs every dynamic chain into the
delegate or refuses it by name (strip_dynamic_act_qdq, its final sweep
included), and the
kernel set run_parity.py registers is derived from the emitted programs
(dump_required_ops.py, which refuses a chooser before writing
required_ops.txt, and run_parity.refuse_portable_choosers after it).

Light: reads required_ops.txt, which run_parity.py regenerates.
"""

from pathlib import Path

import pytest

from executorch.backends.esp32s3.test.parity import run_parity

ROOT = Path(__file__).resolve().parent
# The firmware project: its selective build (scripts/gen_kernels.py) and the
# ExecuTorch component that build writes into.
PROJECT = ROOT.parents[3] / "examples" / "espressif" / "esp32s3"
SCRIPTS = PROJECT / "scripts"


def test_required_ops_register_no_chooser():
    from executorch.backends.esp32s3.test import firmware

    path = firmware.REQUIRED_OPS
    if not path.is_file():
        pytest.skip("required_ops.txt is regenerated by run_parity.py "
                    "(dump_required_ops.py); none here yet")
    assert run_parity.portable_choosers(str(path)) == []


def test_the_guard_sees_a_chooser(tmp_path):
    listing = tmp_path / "required_ops.txt"
    listing.write_text("# Generated by dump_required_ops.py -- do not edit.\n"
                       "aten::add.out\n"
                       "quantized_decomposed::choose_qparams.Tensor_out\n"
                       "quantized_decomposed::quantize_per_tensor.out\n")
    assert run_parity.portable_choosers(str(listing)) == [
        "quantized_decomposed::choose_qparams.Tensor_out"]


def test_gen_kernels_refuses_a_chooser(tmp_path):
    """gen_kernels.py registers ExecuTorch's static quantize/dequantize
    kernels from quantized.yaml (a safety net for static pairs the delegate
    does not absorb) but stops
    before any codegen when the op list names a chooser."""
    import subprocess
    import sys

    listing = tmp_path / "required_ops.txt"
    listing.write_text("aten::add.out\n"
                       "quantized_decomposed::quantize_per_tensor.out\n"
                       "quantized_decomposed::choose_qparams.Tensor_out\n")
    done = subprocess.run(
        [sys.executable, str(SCRIPTS / "gen_kernels.py"), "--required",
         str(listing), "--suffix", "_chooser_probe"],
        cwd=SCRIPTS, capture_output=True, text=True, timeout=120)
    assert done.returncode != 0
    assert "portable choosers" in done.stdout + done.stderr
    assert not (PROJECT / "components/executorch/"
                "generated_kernels_chooser_probe").exists()


def test_host_registers_the_kernels_the_census_counts():
    """The quantized kernels the census counts as registered (test/host.py)
    are the ones the host runner's codegen registers, and none is a chooser."""
    import importlib.util

    from executorch.backends.esp32s3.test.host import QUANTIZED_KERNELS

    spec = importlib.util.spec_from_file_location(
        "codegen_portable", ROOT.parent / "host_runner" / "codegen_portable.py")
    codegen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(codegen)
    assert tuple(codegen.QUANTIZED) == QUANTIZED_KERNELS
    assert not any("choose_qparams" in k for k in QUANTIZED_KERNELS)


@pytest.mark.parametrize("qdq_fast", [True, False])
def test_gen_kernels_registers_the_static_pair_kernels(tmp_path, qdq_fast):
    """A program with a static pair left portable, or a per-tensor dequantize
    by a scale and zero point in one-element tensors (Tensor_out, which the
    host runner registers too), gets ExecuTorch's own quantize/dequantize
    kernels, their sources (kernels/quantized/cpu) in the firmware's source
    list. The per-tensor pair's .out overloads are the op library's exact
    fast paths (ops/qdq_pool.h) for such a program, with those kernels as
    their fallback: the codegen registers the rest, and Esp32KernelVariant.h
    switches the op library's two on -- unless --no-qdq-fast (the A/B build)
    keeps all four from the codegen."""
    import shutil
    import subprocess
    import sys

    tensor_out = "quantized_decomposed::dequantize_per_tensor.Tensor_out"
    pair = ("quantized_decomposed::quantize_per_tensor.out",
            "quantized_decomposed::dequantize_per_tensor.out")
    listing = tmp_path / "required_ops.txt"
    listing.write_text("aten::add.out\n"
                       "quantized_decomposed::dequantize_per_tensor.out\n"
                       "quantized_decomposed::quantize_per_tensor.out\n"
                       "quantized_decomposed::dequantize_per_channel.out\n"
                       f"{tensor_out}\n")
    suffix = "_qprobe" if qdq_fast else "_qprobe_ab"
    component = PROJECT / "components" / "executorch"
    gen = component / f"generated_kernels{suffix}"
    srcs = component / f"generated_kernel_srcs{suffix}.cmake"
    try:
        done = subprocess.run(
            [sys.executable, str(SCRIPTS / "gen_kernels.py"), "--required",
             str(listing), "--suffix", suffix, *([] if qdq_fast else ["--no-qdq-fast"])],
            cwd=SCRIPTS, capture_output=True, text=True, timeout=300)
        assert done.returncode == 0, done.stdout[-2000:] + done.stderr[-2000:]
        # add.out is the Espressif library's override, registered apart.
        registered = 2 if qdq_fast else 4
        assert f"requested {registered} ops, registered {registered}" in done.stdout, done.stdout
        registration = (gen / "RegisterKernelsEverything.cpp").read_text()
        assert f'"{tensor_out}"' in registration
        for name in pair:
            assert (f'"{name}"' in registration) != qdq_fast, (name, registration[-2000:])
        variant = (gen / "Esp32KernelVariant.h").read_text()
        for macro in ("ESP32_GENERATED_FAST_QUANTIZE", "ESP32_GENERATED_FAST_DEQUANTIZE"):
            assert f"#define {macro} {int(qdq_fast)}" in variant, variant
        assert "#define ESP32_GENERATED_FAST_AVG_POOL2D 0" in variant, variant
        listed = srcs.read_text()
        for name in ("op_quantize.cpp", "op_dequantize.cpp"):
            assert f"kernels/quantized/cpu/{name}" in listed, listed
        assert not (gen / "RegisterCPUCustomOps.cpp").exists()
    finally:
        shutil.rmtree(gen, ignore_errors=True)
        srcs.unlink(missing_ok=True)


def _gen_kernels_module(tmp_path):
    """gen_kernels.py imported as a module, its tables only (it parses its
    known arguments at import: an empty operator list here)."""
    import importlib.util
    import sys

    listing = tmp_path / "no_ops.txt"
    listing.write_text("# none\n")
    saved = sys.argv
    sys.argv = [str(SCRIPTS / "gen_kernels.py"), "--required", str(listing)]
    try:
        spec = importlib.util.spec_from_file_location(
            "gen_kernels_probe", SCRIPTS / "gen_kernels.py")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
    finally:
        sys.argv = saved
    return module


def _library_table():
    """espressif_ops.cpp's kCustomKernels: [(operator, the #if guarding its
    entry)], read from the source."""
    import re

    source = (ROOT.parents[1] / "ops" / "espressif_ops.cpp").read_text()
    table = source[source.index("static constexpr Kernel kCustomKernels[] = {"):]
    table = table[:table.index("\n};")]
    entries, guard = [], None
    for line in table.splitlines():
        stripped = line.strip()
        if stripped.startswith(("#if", "#ifdef")):
            guard = stripped
        elif stripped.startswith("#endif"):
            guard = None
        match = re.search(r'Kernel\("([^"]*)"', line)
        if match and match.group(1):
            entries.append((match.group(1), guard))
    return entries


def test_every_library_kernel_is_registered_by_its_operator(tmp_path):
    """Every operator the op library registers sits in kCustomKernels under
    the switch gen_kernels.py writes for it (ESP32_OP(<NS>_<NAME>), which is
    ESP32_GENERATED_OP_<NS>_<NAME>), and gen_kernels.py writes a switch for
    every one of them: a firmware registers, and links, only the kernels its
    programs name. The q/dq/pool fast paths, the element-wise row copy and the
    opt-in fast LayerNorm keep their own switches."""
    gen = _gen_kernels_module(tmp_path)
    own = {"quantized_decomposed::quantize_per_tensor.out":
           "#if ESP32_GENERATED_FAST_QUANTIZE",
           "quantized_decomposed::dequantize_per_tensor.out":
           "#if ESP32_GENERATED_FAST_DEQUANTIZE",
           "aten::avg_pool2d.out": "#if ESP32_GENERATED_FAST_AVG_POOL2D",
           "aten::native_layer_norm.out": "#ifdef ESP32_FAST_LAYERNORM",
           # The element-wise row copy (ops/elementwise.h), taken as the
           # q/dq/pool paths are, with --elementwise-fast.
           "aten::constant_pad_nd.out": "#if ESP32_GENERATED_EW_CONSTANT_PAD"}
    entries = _library_table()
    gated = []
    for op, guard in entries:
        if op in own:
            assert guard == own[op], (op, guard)
            continue
        macro = gen.library_macro(op)
        assert guard is not None and f"ESP32_OP({macro[len('ESP32_GENERATED_OP_'):]})" \
            in guard, (op, guard, macro)
        gated.append(op)
    assert sorted(gated) == sorted(gen.LIBRARY_OPS), (
        sorted(set(gated) ^ set(gen.LIBRARY_OPS)))
    assert len({gen.library_macro(op) for op in gen.LIBRARY_OPS}) == len(
        gen.LIBRARY_OPS)


def test_gen_kernels_switches_on_only_the_named_library_kernels(tmp_path):
    """The story's operator list (no layer_norm2d, no K-cache kernels, no
    aten::div): Esp32KernelVariant.h switches on exactly the library kernels
    the list names, and defines every other switch as 0 -- a firmware links
    nothing of an operator its programs never run (the story would link
    about 13.5 KB of such kernels)."""
    import shutil
    import subprocess
    import sys

    gen = _gen_kernels_module(tmp_path)
    named = ["aten::_softmax.out", "aten::add.out", "aten::bmm.out",
             "aten::index_put_", "aten::mul.out", "aten::cat.out",
             "espressif::attn_tail.out", "espressif::rmsnorm.out",
             "espressif::rope.out", "espressif::quantize_rows_i8.out"]
    listing = tmp_path / "required_ops.txt"
    listing.write_text("".join(op + "\n" for op in named))
    suffix = "_libprobe"
    component = PROJECT / "components" / "executorch"
    out = component / f"generated_kernels{suffix}"
    srcs = component / f"generated_kernel_srcs{suffix}.cmake"
    try:
        done = subprocess.run(
            [sys.executable, str(SCRIPTS / "gen_kernels.py"), "--required",
             str(listing), "--suffix", suffix],
            cwd=SCRIPTS, capture_output=True, text=True, timeout=300)
        assert done.returncode == 0, done.stdout[-2000:] + done.stderr[-2000:]
        variant = (out / "Esp32KernelVariant.h").read_text()
        assert "#define ESP32_GENERATED_OPS_SELECTED 1" in variant, variant
        for op in gen.LIBRARY_OPS:
            want = int(op in named)
            assert f"#define {gen.library_macro(op)} {want}\n" in variant, (
                op, variant)
        # Every override's fallback is still compiled: the parity firmware's
        # fast-path check calls each shim and its portable kernel directly.
        listed = srcs.read_text()
        for source in gen.OVERRIDES.values():
            assert f"kernels/portable/cpu/{source}" in listed, (source, listed)
    finally:
        shutil.rmtree(out, ignore_errors=True)
        srcs.unlink(missing_ok=True)
