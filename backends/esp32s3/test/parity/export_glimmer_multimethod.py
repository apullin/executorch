"""Export one cached nano-Glimmer program with prefill and decode methods.

The two static graphs share a memory-planned mutable KV arena and one external
named-data file.  The host oracle deliberately runs prefill first and decode
second against aliased cache tensors; this makes the firmware check a real
cross-method state handoff rather than two independent method smoke tests.
"""

from __future__ import annotations

import json
import os
import tempfile

import torch

from executorch.backends.esp32s3.partition.espressif_partitioner import (
    Esp32Partitioner,
)
from executorch.backends.esp32s3._passes import apply_passes, lower_esp32
from executorch.backends.esp32s3.test.parity.export_glimmer_decode import (
    quantize_reference_modules,
    token_at,
)
from executorch.backends.esp32s3.test.parity.export_glimmer_prefill import checksum
from executorch.examples.espressif.esp32s3.story.glimmer_decode import (
    build,
    build_prefill,
)
from executorch.backends.esp32s3.utils.multimethod import (
    combine_shared_methods,
    shared_memory_planning_pass,
)

from executorch.backends.esp32s3.test import firmware

HERE = os.path.dirname(os.path.abspath(__file__))
# The example firmware project embeds the programs from its main/.
MAIN = str(firmware.MAIN)
EXTERNAL_TAG = "glimmer_weights"

# The one frozen configuration, shared by the fp32-cache fixture and its
# int8-K-cache twin so the two cannot drift apart.
VOCAB = 256
SEQ_LEN = 8
CHUNK_SIZE = 4
COMMON = dict(
    arm="ple", vocab=VOCAB, d_model=64, layers=4, heads=8,
    kv_heads=1, ffn=192, ple_dim=24, seq_len=SEQ_LEN,
    window=4, softcap=20.0,
)


def _share_reference_cache(prefill, decode):
    """Make the eager entry points view the same eight mutable cache tensors."""
    prefill_buffers = dict(prefill.named_buffers())
    decode_buffers = dict(decode.named_buffers())
    cache_names = sorted(name for name in prefill_buffers if "cache_" in name)
    if not cache_names or cache_names != sorted(
            name for name in decode_buffers if "cache_" in name):
        raise ValueError("prefill/decode cache ABI mismatch in eager oracle")
    for name in cache_names:
        if (prefill_buffers[name].shape != decode_buffers[name].shape
                or prefill_buffers[name].dtype != decode_buffers[name].dtype):
            raise ValueError(f"cache tensor {name} differs between methods")
        setattr(decode, name, prefill_buffers[name])


def _lower(model, inputs, attn_tails):
    edge = lower_esp32(
        torch.export.export(model, inputs),
        [Esp32Partitioner(
            external_weights=EXTERNAL_TAG,
            format_policy="i8",
            quantize_qk=True,
            group_weights=False,
        )],
    )
    # The oracle mirrors espressif::attn_tail in decode and the portable
    # softmax/bmm in prefill, so each method must fuse exactly that many tails.
    report = apply_passes(edge, rmsnorm_expect=31, attn_tail_expect=attn_tails)
    if report["rope_fused"] != 6:
        raise RuntimeError(f"expected six RoPE fusions, got {report}")
    return edge, report


def _write_inputs(prefill_tokens, decode_tokens, prefill_chunk):
    def values(items):
        return ", ".join(str(value) for value in items)

    path = os.path.join(MAIN, "glimmer_multimethod_inputs.h")
    with open(path, "w") as out:
        out.write(
            "// Generated by export_glimmer_multimethod.py; do not edit.\n"
            "#pragma once\n"
            f"static constexpr int kGlimmerPrefillTokens[] = "
            f"{{{values(prefill_tokens)}}};\n"
            f"static constexpr int kGlimmerPrefillChunk = {prefill_chunk};\n"
            f"static constexpr int kGlimmerDecodeTokens[] = "
            f"{{{values(decode_tokens)}}};\n"
            f"static constexpr int kGlimmerDecodeSteps = "
            f"{len(decode_tokens)};\n"
        )
    print("wrote glimmer_multimethod_inputs.h")


def _tokens():
    all_tokens = [token_at(step, VOCAB) for step in range(SEQ_LEN)]
    return all_tokens[:CHUNK_SIZE], all_tokens[CHUNK_SIZE:]


def _reference_checksums(prefill_tokens, decode_tokens, **options):
    """Device-arithmetic eager oracle: identical seeded weights, i8 learned
    ops, dynamic-i8 Q@K, decode's fused attention tail, and (critically) one
    aliased KV state across entry points. Prefill's softmax and P@V are the
    chip's (newlib's expf, shim_bmm_out's fused multiply-adds), but RMSNorm
    and RoPE run in torch, so the oracle is not device-exact; run_parity
    holds these rows to TOL (CACHED)."""
    _, reference_prefill = build_prefill(
        chunk_size=CHUNK_SIZE, reference_dynamic_qk=True, **options, **COMMON)
    _, reference_decode = build(
        reference_dynamic_qk=True, local_ring=True, **options, **COMMON)
    quantize_reference_modules(reference_prefill, "i8")
    quantize_reference_modules(reference_decode, "i8")
    _share_reference_cache(reference_prefill, reference_decode)

    with torch.no_grad():
        prefill_logits = reference_prefill(
            torch.tensor(prefill_tokens), torch.tensor(0))
        prefill_checksum = checksum(prefill_logits)
        print(f"  host shared prefill: pos 0..{CHUNK_SIZE - 1}  "
              f"checksum {prefill_checksum:.6f}")
        decode_checksums = []
        for offset, token in enumerate(decode_tokens):
            pos = CHUNK_SIZE + offset
            logits = reference_decode(torch.tensor([token]), torch.tensor(pos))
            got = checksum(logits)
            decode_checksums.append(got)
            print(f"  host shared decode {offset}: token {token:5d} pos {pos}  "
                  f"checksum {got:.6f}")
    return prefill_checksum, decode_checksums


def main(argv=None):
    if argv:
        raise ValueError("the parity fixture has one frozen configuration")

    prefill_tokens, decode_tokens = _tokens()
    prefill_checksum, decode_checksums = _reference_checksums(
        prefill_tokens, decode_tokens)

    # Prove that this particular numeric oracle can detect a lost handoff. A
    # cache-sharing test whose chosen random weights/tokens happen to produce
    # the same first decode value from an empty cache would be structurally
    # attractive and behaviorally useless.
    _, empty_decode = build(
        reference_dynamic_qk=True, local_ring=True, **COMMON)
    quantize_reference_modules(empty_decode, "i8")
    with torch.no_grad():
        empty_logits = empty_decode(
            torch.tensor([decode_tokens[0]]), torch.tensor(CHUNK_SIZE))
        empty_decode_checksum = checksum(empty_logits)
    state_sensitivity = abs(decode_checksums[0] - empty_decode_checksum)
    if state_sensitivity < 1.0:
        raise RuntimeError(
            "chosen multimethod oracle is insensitive to a cleared KV cache: "
            f"shared={decode_checksums[0]}, empty={empty_decode_checksum}")
    print(f"  cleared-cache negative: {empty_decode_checksum:.6f} "
          f"(delta {state_sensitivity:.6f})")

    cfg, decode = build(local_ring=True, **COMMON)
    _, prefill = build_prefill(chunk_size=CHUNK_SIZE, **COMMON)
    decode_edge, decode_report = _lower(
        decode, (torch.tensor([decode_tokens[0]]), torch.tensor(CHUNK_SIZE)),
        attn_tails=cfg.n_layers)
    prefill_edge, prefill_report = _lower(
        prefill, (torch.tensor(prefill_tokens), torch.tensor(0)), attn_tails=0)
    combined_edge = combine_shared_methods({
        "decode": decode_edge,
        "prefill": prefill_edge,
    })

    from executorch.exir import ExecutorchBackendConfig

    program = combined_edge.to_executorch(config=ExecutorchBackendConfig(
        delegate_alignment=16,
        constant_tensor_alignment=16,
        external_constants=lambda node: EXTERNAL_TAG,
        memory_planning_pass=shared_memory_planning_pass(),
        # In-place KV writes, as the story export does: the parity row's
        # shared-arena and method-reload checks then exercise index_put_ on a
        # mutable buffer shared by prefill and decode.
        run_reinplace_pass=True,
    ))
    pte_path = os.path.join(MAIN, "glimmer_multimethod.pte")
    with open(pte_path, "wb") as out:
        out.write(program.buffer)
    program.write_tensor_data_to_file(MAIN)
    ptd_path = os.path.join(MAIN, f"{EXTERNAL_TAG}.ptd")

    plans = {
        plan.name: list(plan.non_const_buffer_sizes)
        for plan in program.executorch_program.execution_plan
    }
    cache_bytes = sum(
        value.numel() * value.element_size()
        for name, value in decode.named_buffers() if "cache_" in name)
    if set(plans) != {"decode", "prefill"}:
        raise RuntimeError(f"unexpected method set: {sorted(plans)}")
    if not all(len(sizes) == 3 and sizes[2] == cache_bytes
               for sizes in plans.values()):
        raise RuntimeError(
            f"shared mutable arena was not preserved: {plans}, cache={cache_bytes}")

    meta = {
        "architecture": "glimmer-ple-multimethod",
        "weight_format": "i8",
        "vocab": VOCAB,
        "seq_len": SEQ_LEN,
        "chunk_size": CHUNK_SIZE,
        "prefill_tokens": prefill_tokens,
        "decode_tokens": decode_tokens,
        "prefill_checksums": [prefill_checksum],
        "decode_checksums": decode_checksums,
        "empty_decode_first_checksum": empty_decode_checksum,
        "state_sensitivity": state_sensitivity,
        "cache_bytes": cache_bytes,
        "plans": plans,
        "fusions": {"decode": decode_report, "prefill": prefill_report},
    }
    _write_inputs(prefill_tokens, decode_tokens, CHUNK_SIZE)
    with open(os.path.join(MAIN, "glimmer_multimethod_ref.json"), "w") as out:
        json.dump(meta, out, indent=1)
    print(f"wrote glimmer_multimethod.pte {os.path.getsize(pte_path):,} B + "
          f"{EXTERNAL_TAG}.ptd {os.path.getsize(ptd_path):,} B")
    print(f"shared plans: {plans}; mutable cache {cache_bytes:,} B")
    return meta


def _plan_ops(program):
    """Method name -> the emitted instruction names, in plan order."""
    plans = {}
    for plan in program.executorch_program.execution_plan:
        names = []
        for instruction in plan.chains[0].instructions:
            args = instruction.instr_args
            if hasattr(args, "op_index"):
                op = plan.operators[args.op_index]
                names.append(op.name + (f".{op.overload}" if op.overload else ""))
            else:
                names.append(type(args).__name__)
        plans[plan.name] = names
    return plans


def export_kcache_variant(fp32_meta):
    """The same fixture with the persistent int8 K cache (kcache_i8.py).

    Same seeded weights, tokens and prefill -> decode handoff. K is int8 codes
    plus one fp32 scale per row, quantised once when written, and the cache
    rows are written in place (run_reinplace_pass), as in the fp32 fixture and
    the story export. Two claims are checked here, at export, before any
    device runs:

      * the host oracle reproduces the fp32-cache fixture's checksums EXACTLY,
        so the device rows answer to the very same numbers;
      * the named data is the fp32 fixture's PTD byte for byte, so the
        firmware loads this program against the same glimmerw partition.
    """
    from executorch.exir import ExecutorchBackendConfig

    prefill_tokens, decode_tokens = _tokens()
    prefill_checksum, decode_checksums = _reference_checksums(
        prefill_tokens, decode_tokens, int8_kcache=True)
    same = (prefill_checksum == fp32_meta["prefill_checksums"][0]
            and decode_checksums == fp32_meta["decode_checksums"])
    if not same:
        raise RuntimeError(
            "int8 K cache oracle differs from the fp32-cache oracle: "
            f"prefill {prefill_checksum!r} vs {fp32_meta['prefill_checksums']}, "
            f"decode {decode_checksums} vs {fp32_meta['decode_checksums']}")
    print("  int8 K cache oracle == fp32-cache oracle, all "
          f"{1 + len(decode_checksums)} checksums exactly")

    _, decode = build(local_ring=True, int8_kcache=True, **COMMON)
    _, prefill = build_prefill(chunk_size=CHUNK_SIZE, int8_kcache=True, **COMMON)
    decode_edge, decode_report = _lower(
        decode, (torch.tensor([decode_tokens[0]]), torch.tensor(CHUNK_SIZE)),
        attn_tails=COMMON["layers"])
    prefill_edge, prefill_report = _lower(
        prefill, (torch.tensor(prefill_tokens), torch.tensor(0)), attn_tails=0)
    combined_edge = combine_shared_methods({
        "decode": decode_edge,
        "prefill": prefill_edge,
    })
    program = combined_edge.to_executorch(config=ExecutorchBackendConfig(
        delegate_alignment=16,
        constant_tensor_alignment=16,
        external_constants=lambda node: EXTERNAL_TAG,
        memory_planning_pass=shared_memory_planning_pass(),
        run_reinplace_pass=True,
    ))
    pte_path = os.path.join(MAIN, "glimmer_multimethod_kc8.pte")
    with open(pte_path, "wb") as out:
        out.write(program.buffer)
    with tempfile.TemporaryDirectory() as scratch:
        program.write_tensor_data_to_file(scratch)
        with open(os.path.join(scratch, f"{EXTERNAL_TAG}.ptd"), "rb") as f:
            ptd = f.read()
    with open(os.path.join(MAIN, f"{EXTERNAL_TAG}.ptd"), "rb") as f:
        if f.read() != ptd:
            raise RuntimeError(
                "the int8-K-cache fixture's named data differs from "
                f"{EXTERNAL_TAG}.ptd; it cannot share the glimmerw partition")

    layers = COMMON["layers"]
    plans = {plan.name: list(plan.non_const_buffer_sizes)
             for plan in program.executorch_program.execution_plan}
    cache_bytes = sum(
        value.numel() * value.element_size()
        for name, value in decode.named_buffers() if "cache_" in name)
    if not all(len(sizes) == 3 and sizes[2] == cache_bytes
               for sizes in plans.values()):
        raise RuntimeError(
            f"shared mutable arena was not preserved: {plans}, cache={cache_bytes}")
    ops = _plan_ops(program)
    for method, names in ops.items():
        if (names.count("espressif::quantize_rows_i8.out") != layers
                or names.count("aten::index_put_") != 3 * layers
                or any(name.startswith("aten::copy_") for name in names)):
            raise RuntimeError(
                f"{method}: expected {layers} quantisers and {3 * layers} "
                f"in-place index_put_, no copy_: {sorted(set(names))}")

    meta = dict(fp32_meta)
    meta.update({
        "architecture": "glimmer-ple-multimethod-int8-kcache",
        "prefill_checksums": [prefill_checksum],
        "decode_checksums": decode_checksums,
        "cache_bytes": cache_bytes,
        "fp32_cache_bytes": fp32_meta["cache_bytes"],
        "plans": plans,
        "instructions": {method: len(names) for method, names in ops.items()},
        "fusions": {"decode": decode_report, "prefill": prefill_report},
    })
    meta.pop("empty_decode_first_checksum", None)
    meta.pop("state_sensitivity", None)
    with open(os.path.join(MAIN, "glimmer_multimethod_kc8_ref.json"), "w") as out:
        json.dump(meta, out, indent=1)
    print(f"wrote glimmer_multimethod_kc8.pte {os.path.getsize(pte_path):,} B "
          f"(named data identical to {EXTERNAL_TAG}.ptd)")
    print(f"int8 K cache: mutable state {fp32_meta['cache_bytes']:,} -> "
          f"{cache_bytes:,} B; plans {plans}; instructions {meta['instructions']}")
    return meta


if __name__ == "__main__":
    export_kcache_variant(main())
