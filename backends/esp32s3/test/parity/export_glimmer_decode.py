"""Export a small Glimmer decode step for multi-step QEMU parity.

The program fills the ``decode.pte`` runner slot with the story model's
architecture at reduced size: four Glimmer layers, the 3-local/1-global
schedule, compact GQA cache, PLE, dynamic-i8 Q@K, centered and weightless
RMSNorm, sigmoid attention gates, SwiGLU, an untied head, output scaling, and
softcap.

The default is per-row i8.  ``--format i4 --output decode_i4`` emits an
independent external-weight sibling and exact oracle, so packed storage is
validated through the complete cached architecture rather than only micro rows.
Group-128 lowering is a separate control: both architecture variants use one
scale per learned row.
"""

import argparse
import json
import os

import numpy as np
import torch
import torch.nn as nn

from executorch.backends.esp32s3.partition.espressif_partitioner import (
    Esp32Partitioner,
)
from executorch.backends.esp32s3._passes import apply_passes, lower_esp32
from executorch.examples.espressif.esp32s3.story.glimmer_decode import build
from executorch.backends.esp32s3.test.reference import (
    addmm_iq_absmax,
    embedding_iq_absmax,
)

from executorch.backends.esp32s3.test import firmware

HERE = os.path.dirname(os.path.abspath(__file__))
# The example firmware project embeds the programs from its main/.
MAIN = str(firmware.MAIN)


def token_at(step, vocab):
    """Deterministic host sequence emitted verbatim for the device runner."""
    return (step * 37 + 3) % vocab


def write_runner_inputs(tokens):
    """Make the firmware consume the exact sequence used for the host oracle."""
    path = os.path.join(MAIN, "decode_inputs.h")
    values = ", ".join(str(token) for token in tokens)
    with open(path, "w") as out:
        out.write(
            "// Generated by export_glimmer_decode.py; do not edit.\n"
            "#pragma once\n"
            f"static constexpr int kDecodeTokens[] = {{{values}}};\n"
            f"static constexpr int kDecodeSteps = {len(tokens)};\n"
        )
    print("wrote decode_inputs.h")


def quantize_reference_modules(model, fmt="i8"):
    """Replace learned ops with the delegate's exact selected-format arithmetic."""

    def make_linear(mod):
        weight = mod.weight.detach().numpy().astype(np.float32)
        bias = (mod.bias.detach().numpy().astype(np.float32)
                if mod.bias is not None else np.zeros(weight.shape[0], np.float32))

        def forward(inp):
            k = inp.shape[-1]
            flat = inp.detach().reshape(-1, k).contiguous().numpy().astype(np.float32)
            out = addmm_iq_absmax(flat, weight, bias, fmt=fmt)
            return torch.from_numpy(out).reshape(*inp.shape[:-1], weight.shape[0])

        return forward

    def make_embedding(mod):
        table = mod.weight.detach().numpy().astype(np.float32)

        def forward(indices):
            flat = indices.detach().reshape(-1).numpy()
            rows = embedding_iq_absmax(table, flat, fmt=fmt)
            return torch.from_numpy(rows).reshape(*indices.shape, table.shape[1])

        return forward

    for module in model.modules():
        if isinstance(module, nn.Linear):
            module.forward = make_linear(module)
        elif isinstance(module, nn.Embedding):
            module.forward = make_embedding(module)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--vocab", type=int, default=256)
    ap.add_argument("--seq-len", type=int, default=8)
    ap.add_argument("--steps", type=int, default=8)
    ap.add_argument("--external", action="store_true", default=True)
    ap.add_argument("--format", choices=("i4", "i8"), default="i8")
    ap.add_argument("--output", default="decode")
    args = ap.parse_args(argv)
    if args.steps > args.seq_len:
        raise ValueError("steps cannot exceed the static cache length")

    common = dict(
        arm="ple", vocab=args.vocab, d_model=64, layers=4, heads=8,
        kv_heads=1, ffn=192, ple_dim=24, seq_len=args.seq_len,
        window=min(4, args.seq_len), softcap=20.0,
    )

    # Host side mirrors both the selected-format learned ops and OP_BMM_DYN_I8. It is a
    # separate instance because exporting the decomposed reference quantiser
    # would hide the raw BMM the partitioner must claim.
    cfg, reference = build(**common, reference_dynamic_qk=True, local_ring=True)
    quantize_reference_modules(reference, args.format)
    refs = []
    with torch.no_grad():
        for step in range(args.steps):
            tok_id = token_at(step, args.vocab)
            logits = reference(torch.tensor([tok_id]), torch.tensor(step))
            flat = logits.reshape(-1)
            checksum = sum(float(flat[i]) * (i + 1) for i in range(flat.numel()))
            refs.append(checksum)
            print(f"  host Glimmer step {step}: token {tok_id:5d} pos {step}  "
                  f"checksum {checksum:.6f}")

    _, model = build(**common, local_ring=True)
    inputs = (torch.tensor([token_at(0, args.vocab)]), torch.tensor(0))
    exported = torch.export.export(model, inputs)
    external_tag = f"{args.output}_weights"
    lowered = lower_esp32(
        exported, [Esp32Partitioner(
            external_weights=external_tag if args.external else False,
            format_policy=args.format,
            quantize_qk=True,
            group_weights=False,
        )])
    # attn_tail_expect: the host oracle mirrors espressif::attn_tail for every
    # layer's tail, so a tail left portable would be a reference mismatch.
    report = apply_passes(lowered, rmsnorm_expect=7 * cfg.n_layers + 3,
                          attn_tail_expect=cfg.n_layers)
    assert report["rope_fused"] == 6, report

    sig = lowered.exported_program().graph_signature
    mutated = set(sig.buffers_to_mutate.values())
    expected_mutations = {
        f"{kind}cache_{layer}"
        for layer in range(cfg.n_layers)
        for kind in ("k", "v")
    }
    assert expected_mutations <= mutated, (
        f"missing cache mutations: {sorted(expected_mutations - mutated)}")

    from executorch.exir import ExecutorchBackendConfig

    et_cfg = ExecutorchBackendConfig(
        delegate_alignment=16,
        constant_tensor_alignment=16,
    )
    if args.external:
        et_cfg.external_constants = lambda node: external_tag
    program = lowered.to_executorch(config=et_cfg)

    pte = os.path.join(MAIN, f"{args.output}.pte")
    with open(pte, "wb") as out:
        out.write(program.buffer)
    extra = ""
    if args.external:
        program.write_tensor_data_to_file(MAIN)
        ptd = os.path.join(MAIN, f"{external_tag}.ptd")
        extra = f" + {external_tag}.ptd {os.path.getsize(ptd):,} B"
    print(f"\nwrote {args.output}.pte {os.path.getsize(pte):,} B{extra}")
    print(f"mutable buffers: {sorted(mutated)}")

    tokens = [token_at(step, args.vocab) for step in range(args.steps)]
    meta = {
        "architecture": "glimmer-ple",
        "weight_format": args.format,
        "vocab": args.vocab,
        "seq_len": args.seq_len,
        "steps": args.steps,
        "tokens": tokens,
        "checksums": refs,
    }
    write_runner_inputs(tokens)
    with open(os.path.join(MAIN, f"{args.output}_ref.json"), "w") as out:
        json.dump(meta, out, indent=1)
    print(f"wrote {args.output}_ref.json")
    return meta


if __name__ == "__main__":
    main()
