"""expf_golden.h: newlib expf's results, as quantizer/mirrors.py expf_newlib
computes them, for expf_check.cpp to hold the chip's expf to.

The softmax override (ops/espressif_ops.cpp shim_softmax_out) takes exp from
newlib's expf on the chip and from newlib_expf.h's transcription of it on the
host; test/reference.py's softmax mirror uses expf_newlib, the same
transcription in numpy. Their only independent check is this one: the cases
below run through the chip's own expf (the parity firmware, under QEMU and
on the board) and the host's transcription (--selftest), against these
mirror bits.

  boundary  every branch threshold of newlib's __ieee754_expf (ef_exp.c), at
            the threshold's bit pattern and one ulp either side, both signs
            where the branch reads |x|: 0, |x| = 2^-23, ln2/2 and 1.5 ln2,
            the overflow and underflow thresholds (0x42b17217, 0x42cff1b5),
            the onset of subnormal results (ln FLT_MIN = -87.34) and of the
            k < -125 rescale (-125.5 ln2 = -86.99), and the infinities
  range     a xorshift32 stream mapped to [-104, 24): fl((s >> 8) 2^-17) - 104
  bits      a xorshift32 stream of finite bit patterns with |x| < 128
            (exponent field mod 0x86), subnormals included

Each stream is checked by the FNV-1a of its results' bytes. NaN inputs are
left out: their payload bits are not part of newlib's contract.

    python expf_golden.py          # rewrite expf_golden.h
"""

from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent
HEADER = ROOT / "expf_golden.h"

STREAMS = (("range", 0x12345678, 4096, 0), ("bits", 0x9E3779B9, 4096, 1))


def _bits(value):
    return int(np.float32(value).view(np.uint32))


def _around(bits, span=1):
    return [(bits + d) & 0xFFFFFFFF for d in range(-span, span + 1)]


def boundary_inputs():
    """The boundary cases' input bit patterns, in order, without repeats."""
    cases = [0x00000000, 0x80000000, 0x00000001, 0x80000001, 0x007FFFFF,
             0x00800000, 0x7F800000, 0xFF800000]
    for threshold in (0x34000000, 0x3EB17218, 0x3F851592):
        cases += _around(threshold) + _around(threshold | 0x80000000)
    cases += _around(0x42B17217)           # overflow: x > 88.72283935546875
    cases += _around(0xC2CFF1B5)           # underflow: x < -103.972084
    for x in (np.log(np.float64(2.0) ** -126), -125.5 * np.log(2.0)):
        cases += _around(_bits(x), span=2)  # subnormal results; k < -125
    for x in (1.0, -1.0, 0.5, -0.5, 10.0, -10.0, 88.0, -88.0, -100.0, 50.0,
              -50.0, 3.0, -3.0, 0.1, -0.1):
        cases.append(_bits(x))
    seen, out = set(), []
    for bits in cases:
        if bits not in seen:
            seen.add(bits)
            out.append(bits)
    return out


def xorshift32(seed, count):
    state, out = seed, []
    for _ in range(count):
        state ^= (state << 13) & 0xFFFFFFFF
        state ^= state >> 17
        state ^= (state << 5) & 0xFFFFFFFF
        out.append(state)
    return np.array(out, dtype=np.uint32)


def stream_inputs(family, seed, count):
    """expf_check.cpp's stream: the same xorshift32 states, the same map."""
    states = xorshift32(seed, count)
    if family == 0:
        steps = (states >> 8).astype(np.float32) * np.float32(2.0 ** -17)
        return (steps.astype(np.float32) - np.float32(104.0)).astype(np.float32)
    exponent = ((states >> 23) & 0xFF) % 0x86
    bits = (states & np.uint32(0x807FFFFF)) | (exponent.astype(np.uint32) << 23)
    return bits.astype(np.uint32).view(np.float32)


def fnv1a(words):
    h = 2166136261
    for byte in np.asarray(words, dtype=np.uint32).astype("<u4").tobytes():
        h = ((h ^ byte) * 16777619) & 0xFFFFFFFF
    return h


def expected():
    """(boundary [(x bits, y bits)], streams [(name, seed, count, family, fnv)])."""
    from executorch.backends.esp32s3.quantizer.mirrors import expf_newlib

    xs = np.array(boundary_inputs(), dtype=np.uint32)
    ys = expf_newlib(xs.view(np.float32)).view(np.uint32)
    boundary = list(zip((int(x) for x in xs), (int(y) for y in ys)))
    streams = []
    for name, seed, count, family in STREAMS:
        values = expf_newlib(stream_inputs(family, seed, count))
        streams.append((name, seed, count, family, fnv1a(values.view(np.uint32))))
    return boundary, streams


def golden_header():
    boundary, streams = expected()
    lines = [
        "// Generated by expf_golden.py from quantizer/mirrors.py expf_newlib: do not",
        "// edit. expf_check.cpp holds the chip's expf (and the host's transcription,",
        "// newlib_expf.h) to these bits.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace espressif {",
        "namespace expf_check {",
        "",
        "struct Case {",
        "  uint32_t x;  // input bits",
        "  uint32_t y;  // expf(x) bits",
        "};",
        "",
        "struct Stream {",
        "  const char* name;",
        "  uint32_t seed;",
        "  uint32_t count;",
        "  uint32_t family;  // 0: fl((s >> 8) 2^-17) - 104; 1: finite bits, |x| < 128",
        "  uint32_t fnv;     // FNV-1a of the results' bytes",
        "};",
        "",
        "constexpr Case kBoundary[] = {",
    ]
    for x, y in boundary:
        lines.append(f"    {{0x{x:08x}u, 0x{y:08x}u}},")
    lines += ["};", "", "constexpr Stream kStreams[] = {"]
    for name, seed, count, family, fnv in streams:
        lines.append(f'    {{"{name}", 0x{seed:08x}u, {count}u, {family}u, 0x{fnv:08x}u}},')
    lines += ["};", "", "}  // namespace expf_check", "}  // namespace espressif", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    HEADER.write_text(golden_header())
    print(f"wrote {HEADER}")
