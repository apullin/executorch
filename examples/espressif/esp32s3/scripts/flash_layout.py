"""Single source of truth for the lean 16 MiB ExecuTorch model region.

The region from PTE_OFFSET to the end of flash holds one model: its program
(PTE, partition subtype 0x43) and its weights (PTD, subtype 0x44). How that
region is split is a property of the MODEL, not of the board: the story
Glimmer's two-method program needs 170 KB, the flash-scale speed-check model's
weights need 15.14 MB, and no single split holds both. Loaders find the two
partitions by subtype, so the split may move per build.

- The DEFAULT split (below, and the example's `partitions_ple.csv`)
  is used whenever a model fits it, so most builds never change the table.
- A model that does not fit gets `layout_for(pte, ptd)`: the program partition
  sized to the program in whole 4 KiB pages, every remaining byte to weights.
  `use_layout(build_dir, layout)` writes that table into the build directory
  and points the build at it.
"""

import os
import re


FLASH_END = 0x1000000
# NVS: the story firmware keeps the last story it wrote here, for the panel at boot.
NVS_OFFSET, NVS_SIZE = 0x9000, 0x5000
PTE_OFFSET = 0x170000
# Default split: 36 pages of program (147,456 B); a model whose program or
# weights do not fit gets a sized split (layout_for).
PTE_LIMIT = 0x24000
PTD_OFFSET = PTE_OFFSET + PTE_LIMIT
PTD_LIMIT = FLASH_END - PTD_OFFSET
ET_PACKAGE_BUDGET = FLASH_END - PTE_OFFSET
DEFAULT_CSV = "partitions_ple.csv"

# These pin the default split; partitions_ple.csv carries the same numbers.
assert PTD_OFFSET == 0x194000
assert PTD_LIMIT == 0xE6C000
assert PTE_LIMIT + PTD_LIMIT == ET_PACKAGE_BUDGET


def partition_aligned(size: int) -> int:
    """ESP partition payload size rounded to its 4 KiB allocation."""
    return (size + 0xFFF) & ~0xFFF


def layout_for(pte_bytes: int, ptd_bytes: int) -> dict:
    """The flash split for one model: the default when it fits, else sized.

    Raises ValueError when program and weights together exceed the region.
    """
    if pte_bytes <= PTE_LIMIT and ptd_bytes <= PTD_LIMIT:
        return {"default": True, "pte_offset": PTE_OFFSET, "pte_size": PTE_LIMIT,
                "ptd_offset": PTD_OFFSET, "ptd_size": PTD_LIMIT}
    pte_size = partition_aligned(max(pte_bytes, 1))
    ptd_offset = PTE_OFFSET + pte_size
    ptd_size = FLASH_END - ptd_offset
    if ptd_bytes > ptd_size:
        raise ValueError(
            f"model does not fit the {ET_PACKAGE_BUDGET:,}-byte model region: "
            f"program {pte_bytes:,} B ({pte_size:,} B in pages) + weights "
            f"{ptd_bytes:,} B > {ET_PACKAGE_BUDGET:,} B")
    return {"default": False, "pte_offset": PTE_OFFSET, "pte_size": pte_size,
            "ptd_offset": ptd_offset, "ptd_size": ptd_size}


def describe(layout: dict, pte_bytes: int, ptd_bytes: int) -> str:
    kind = "default split" if layout["default"] else "split sized to this model"
    return (f"{kind}: program {pte_bytes:,} of {layout['pte_size']:,} B "
            f"@0x{layout['pte_offset']:x}, weights {ptd_bytes:,} of "
            f"{layout['ptd_size']:,} B @0x{layout['ptd_offset']:x} "
            f"({layout['ptd_size'] - ptd_bytes:,} B spare)")


def partition_rows(layout: dict) -> list:
    """(name, type, subtype, offset, size) rows of the lean table."""
    return [
        ("nvs", "data", "nvs", NVS_OFFSET, NVS_SIZE),
        ("phy_init", "data", "phy", 0xF000, 0x1000),
        ("factory", "app", "factory", 0x10000, PTE_OFFSET - 0x10000),
        ("pleprog", "data", "0x43", layout["pte_offset"], layout["pte_size"]),
        ("pleweights", "data", "0x44", layout["ptd_offset"], layout["ptd_size"]),
    ]


def partition_csv(layout: dict) -> str:
    lines = ["# Generated by flash_layout.py for one model; do not edit.",
             "# Name,     Type, SubType,  Offset,    Size,     Flags"]
    for name, kind, subtype, offset, size in partition_rows(layout):
        lines.append(f"{name + ',':<11} {kind + ',':<5} {subtype + ',':<9} "
                     f"0x{offset:x},{' ' * max(1, 10 - len(hex(offset)))}0x{size:x},")
    return "\n".join(lines) + "\n"


def use_layout(build_dir: str, layout: dict) -> str:
    """Point one ESP-IDF build directory at this layout's partition table.

    Returns an sdkconfig defaults file to append to SDKCONFIG_DEFAULTS (it
    decides a fresh build); an existing `<build_dir>/sdkconfig` is rewritten
    too, because a present sdkconfig outranks every defaults file. The default
    layout points back at the tracked table, so a build directory that once
    held a sized table returns to the default cleanly.
    """
    os.makedirs(build_dir, exist_ok=True)
    if layout["default"]:
        table = DEFAULT_CSV
    else:
        table = os.path.join(os.path.abspath(build_dir), "partitions_model.csv")
        with open(table, "w") as out:
            out.write(partition_csv(layout))
    settings = {
        "CONFIG_PARTITION_TABLE_CUSTOM": "y",
        "CONFIG_PARTITION_TABLE_CUSTOM_FILENAME": f'"{table}"',
        "CONFIG_PARTITION_TABLE_FILENAME": f'"{table}"',
    }
    defaults = os.path.join(os.path.abspath(build_dir), "sdkconfig.layout")
    with open(defaults, "w") as out:
        out.write("".join(f"{key}={value}\n" for key, value in settings.items()))
    sdkconfig = os.path.join(build_dir, "sdkconfig")
    if os.path.exists(sdkconfig):
        text = open(sdkconfig).read()
        for key, value in settings.items():
            pattern = re.compile(rf"^{key}=.*$", re.M)
            text = (pattern.sub(f"{key}={value}", text) if pattern.search(text)
                    else text + f"{key}={value}\n")
        with open(sdkconfig, "w") as out:
            out.write(text)
    return defaults


def defaults_disagree(build_dir: str, defaults: str) -> list:
    """The CONFIG_ keys whose value in an existing <build_dir>/sdkconfig differs
    from `defaults` (a missing key counts; no sdkconfig yet means none)."""
    sdkconfig = os.path.join(build_dir, "sdkconfig")
    if not os.path.exists(sdkconfig):
        return []
    have = {}
    for line in open(sdkconfig):
        line = line.strip()
        if line.startswith("CONFIG_") and "=" in line:
            key, _, value = line.partition("=")
            have[key] = value
        elif line.startswith("# CONFIG_") and line.endswith(" is not set"):
            have[line[2:-len(" is not set")]] = "n"
    stale = []
    for line in open(defaults):
        key, sep, value = line.strip().partition("=")
        if key.startswith("CONFIG_") and sep and have.get(key) != value:
            stale.append(key)
    return stale


def pin_defaults(build_dir: str, defaults: str) -> None:
    """Write a defaults file's settings into an existing <build_dir>/sdkconfig.

    The same rule as use_layout: a present sdkconfig outranks every defaults
    file, so a build directory made before a setting was added would keep
    building without it. An option that is off reads "# CONFIG_X is not set";
    that line is replaced too.
    """
    sdkconfig = os.path.join(build_dir, "sdkconfig")
    if not os.path.exists(sdkconfig):
        return
    text = open(sdkconfig).read()
    for line in open(defaults):
        key, sep, value = line.strip().partition("=")
        if not key.startswith("CONFIG_") or not sep:
            continue
        setting = f"{key}={value}"
        current = re.compile(rf"^(# {key} is not set|{key}=.*)$", re.M)
        text = (current.sub(lambda _: setting, text) if current.search(text)
                else text + setting + "\n")
    with open(sdkconfig, "w") as out:
        out.write(text)
