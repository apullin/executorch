"""Render nano_zoo/results/*.<size>.json as the zoo's census table.

Pure stdlib (never imports torch).

    python examples/espressif/nano_zoo/census.py [--size device|ci]   # writes CENSUS.md
"""

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent

COLUMNS = ("Family | Params | MB | Arena MB | Status | Delegates | Portable ops | On the fast path "
           "| vs device arithmetic | vs fp32 | Lowering | Top portable ops / error")


def short(op):
    """'espressif.rmsnorm.default' -> 'rmsnorm', 'add.Tensor' -> 'add'."""
    parts = op.split(".")
    if parts[0] in ("dim_order_ops", "espressif", "quantized_decomposed") and len(parts) > 1:
        parts = parts[1:]
    return parts[0]


def row(r):
    params = r.get("params")
    size = r.get("pte_bytes", 0) + r.get("ptd_bytes", 0)
    mb = f"{size / 1e6:.2f}" + ("" if r.get("fits_flash", True) else " (too big)") if size else ""
    arena = f"{r['arena_bytes'] / 1e6:.2f}" if r.get("arena_bytes") is not None else ""
    fast = ""
    if params and "portable_constant_elems" in r:
        fast = f"{100 * max(0.0, 1 - r['portable_constant_elems'] / params):.1f}%"
    device = r.get("vs_device", {})
    fp32 = r.get("vs_fp32", {})
    if "error" in r:
        detail = f"{r['stage']}: {r['error']['type']}: {r['error']['message'][:120]}"
    elif r.get("status") == "no-kernel":
        detail = "no kernel: " + ", ".join(r["ops"]["no_kernel"])
    else:
        detail = ", ".join(f"{short(op)} x{n}" for op, n in sorted(
            r.get("top_real_portable", {}).items(), key=lambda kv: -kv[1])[:5])
    detail = detail.replace("|", "\\|").replace("\n", " ")
    return " | ".join([
        r["family"],
        f"{params / 1e6:.1f}M" if params else "",
        mb,
        arena,
        r.get("status", "?"),
        str(r.get("delegates", "")),
        str(r.get("real_portable_ops", "")),
        fast,
        f"{device['cosine']:.4f}" if device else "",
        f"{fp32['cosine']:.3f}" if fp32 else "",
        f"{r.get('seconds', {}).get('lower', '')}s" if r.get("seconds") else "",
        detail,
    ])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--size", choices=("device", "ci"), default="device")
    args = ap.parse_args()
    records = [json.loads(p.read_text())
               for p in sorted((HERE / "results").glob(f"*.{args.size}.json"))]
    lines = [
        f"# Nano zoo census ({args.size} size)",
        "",
        "Generated by nano_zoo/census.py from nano_zoo/results. Columns:",
        "",
        "- **MB**: lowered program plus weights; the board's model region holds 15.27 MB.",
        "- **Arena MB**: the program's planned activation memory (memory_plan=\"esp32\").",
        "- **Portable ops**: real work left outside the delegates (data movement excluded).",
        "- **On the fast path**: share of the parameters inside delegates.",
        "- **vs device arithmetic**: cosine of the host runner's output against the same",
        "  model under int4 weights and int8 activations (the correctness gate, >= 0.99).",
        "- **vs fp32**: the same against the fp32 model: what quantisation costs a",
        "  random-weight model, not a defect.",
        "",
        "| " + COLUMNS + " |",
        "|" + "---|" * len(COLUMNS.split(" | ")),
    ]
    lines += ["| " + row(r) + " |" for r in records]
    commits = sorted({r.get("commit", "?") for r in records})
    lines += ["", f"Backend commit(s): {', '.join(commits)}."]
    out = HERE / ("CENSUS.md" if args.size == "device" else f"CENSUS.{args.size}.md")
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
